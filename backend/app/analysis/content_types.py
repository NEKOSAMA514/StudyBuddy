"""共用材料类型及各类型的完整写作要求。"""
CONTENT_TYPES = {
    "课程或教材": "课程或教材：解释概念、知识关系、原理与适用条件；例题保留题意、原文关键步骤和结论，必要代码保持完整；易错点或复习要点有依据时再列。",
    "操作教程": "操作教程：围绕目标交代前提、操作、目的与原文给出的成功标准，保留必要命令、参数和排错线索。",
    "观点讲解或评论": "观点讲解或评论：串联主张、论据、推理与局限，明确谁提出观点、哪些是材料陈述的事实；多个立场确需对照时再用归因表。",
    "资讯或事件记录": "资讯或事件记录：突出发生了什么及结果，交代材料提供的人物、时间、地点、原因与过程，不强凑5W1H表。",
    "经验分享": "经验分享：提炼经历、做法、得失及适用条件；有价值的语录须逐字引用，不把个人经验泛化为普遍结论。",
    "研究、报告或数据资料": "研究、报告或数据资料：围绕研究问题或业务问题组织方法、指标、单位、统计口径、比较与结论，保留必要数值和限制，不逐行复述表格。",
}


def complete_content_type(value):
    value = CONTENT_TYPES.get(value.strip(), value.strip())
    if value not in CONTENT_TYPES.values():
        raise ValueError("content_type_must_be_a_supported_type")
    return value
